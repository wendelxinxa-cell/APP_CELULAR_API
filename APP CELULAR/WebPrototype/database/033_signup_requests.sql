BEGIN;

-- Cadastro público: registra o pedido, cria o Auth com a senha escolhida e aguarda Zeus.
CREATE TABLE IF NOT EXISTS chat.solicitacao_cadastro
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL,
    nome TEXT NOT NULL,
    empresa_id BIGINT NOT NULL CHECK (empresa_id > 0),
    status TEXT NOT NULL DEFAULT 'PENDENTE' CHECK (status IN ('PENDENTE','APROVADO','RECUSADO')),
    auth_uid UUID NULL REFERENCES auth.users(id) ON DELETE SET NULL,
    email_verificado_em TIMESTAMPTZ NULL,
    usuario_id BIGINT NULL,
    criada_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    analisada_em TIMESTAMPTZ NULL,
    analisada_por UUID NULL REFERENCES auth.users(id) ON DELETE SET NULL
);
ALTER TABLE chat.solicitacao_cadastro ADD COLUMN IF NOT EXISTS email_verificado_em TIMESTAMPTZ NULL;
CREATE UNIQUE INDEX IF NOT EXISTS ux_solicitacao_cadastro_email_pendente
    ON chat.solicitacao_cadastro (lower(email)) WHERE status='PENDENTE';
CREATE UNIQUE INDEX IF NOT EXISTS ux_solicitacao_cadastro_username_pendente
    ON chat.solicitacao_cadastro (empresa_id, lower(btrim(nome))) WHERE status='PENDENTE';
CREATE UNIQUE INDEX IF NOT EXISTS ux_usuario_auth_username_empresa
    ON chat.usuario_auth (empresa_id, lower(btrim(nome))) WHERE ativo;
ALTER TABLE chat.solicitacao_cadastro ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON chat.solicitacao_cadastro FROM PUBLIC, anon, authenticated;
GRANT ALL ON chat.solicitacao_cadastro TO service_role;
GRANT USAGE, SELECT ON SEQUENCE chat.solicitacao_cadastro_id_seq TO service_role;

CREATE OR REPLACE FUNCTION chat.aprovar_cadastro_pendente(
    p_request_id BIGINT, p_auth_uid UUID, p_usuario_id BIGINT, p_admin_uid UUID)
RETURNS VOID LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_req chat.solicitacao_cadastro%ROWTYPE;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM chat.usuario_auth WHERE auth_uid=p_admin_uid AND ativo AND eh_zeus) THEN
        RAISE EXCEPTION 'Acesso restrito ao usuário Zeus';
    END IF;
    IF p_usuario_id IS NULL OR p_usuario_id <= 0 THEN RAISE EXCEPTION 'Selecione um usuário CATCHAT'; END IF;
    SELECT * INTO v_req FROM chat.solicitacao_cadastro WHERE id=p_request_id AND status='PENDENTE' FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Pedido pendente não encontrado'; END IF;
    IF v_req.email_verificado_em IS NULL OR v_req.auth_uid IS DISTINCT FROM p_auth_uid THEN
        RAISE EXCEPTION 'O solicitante ainda não confirmou o e-mail';
    END IF;
    INSERT INTO chat.usuario_auth (auth_uid,empresa_id,usuario_id,nome,ativo)
        VALUES (p_auth_uid,v_req.empresa_id,p_usuario_id,v_req.nome,TRUE);
    UPDATE chat.solicitacao_cadastro SET status='APROVADO',auth_uid=p_auth_uid,usuario_id=p_usuario_id,
        analisada_em=NOW(),analisada_por=p_admin_uid WHERE id=p_request_id;
END $$;

CREATE OR REPLACE FUNCTION chat.recusar_cadastro_pendente(p_request_id BIGINT, p_admin_uid UUID)
RETURNS VOID LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM chat.usuario_auth WHERE auth_uid=p_admin_uid AND ativo AND eh_zeus) THEN
        RAISE EXCEPTION 'Acesso restrito ao usuário Zeus';
    END IF;
    UPDATE chat.solicitacao_cadastro SET status='RECUSADO',analisada_em=NOW(),analisada_por=p_admin_uid
      WHERE id=p_request_id AND status='PENDENTE';
    IF NOT FOUND THEN RAISE EXCEPTION 'Pedido pendente não encontrado'; END IF;
END $$;
REVOKE ALL ON FUNCTION chat.aprovar_cadastro_pendente(BIGINT,UUID,BIGINT,UUID),
    chat.recusar_cadastro_pendente(BIGINT,UUID) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION chat.aprovar_cadastro_pendente(BIGINT,UUID,BIGINT,UUID),
    chat.recusar_cadastro_pendente(BIGINT,UUID) TO service_role;

NOTIFY pgrst, 'reload schema';

COMMIT;
